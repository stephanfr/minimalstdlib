    using mpsc_type = minstd::mp_sc_growable_ring_queue<uint64_t, 2>;

    struct mpsc_context
    {
        mpsc_type *queue;
        size_t producers;
        size_t items_per_producer;
        uint64_t checksum = 0;
    };

    void mpsc_body(void *arg, size_t tid)
    {
        auto *ctx = static_cast<mpsc_context *>(arg);

        if (tid < ctx->producers)
        {
            for (uint64_t k = 0; k < ctx->items_per_producer; ++k)
            {
                const uint64_t value = (static_cast<uint64_t>(tid) << 32) | (k + 1);
                while (!ctx->queue->push_back(value))
                {
                }
            }
            return;
        }

        const size_t total = ctx->producers * ctx->items_per_producer;
        uint64_t sum = 0;

        for (size_t popped = 0; popped < total;)
        {
            uint64_t value;
            if (ctx->queue->pop_front(value))
            {
                sum += value;
                ++popped;
            }
        }

        ctx->checksum = sum;
    }

    result run_lockfree_mpsc(size_t producers, size_t total_items)
    {
        minstd::pmr::polymorphic_allocator<typename mpsc_type::allocator_type::value_type> alloc(&queue_resource());
        auto *queue = new mpsc_type(alloc, 1024);
        auto *ctx = new mpsc_context();
        ctx->queue = queue;
        ctx->producers = producers;
        ctx->items_per_producer = total_items / producers;

        const double seconds = cmp::run_parallel(producers + 1, mpsc_body, ctx);
        result res{seconds, producers * ctx->items_per_producer, ctx->checksum};
        delete ctx;
        delete queue;
        return res;
    }

