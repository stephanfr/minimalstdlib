    struct alloc_context
    {
        minstd::pmr::memory_resource *resource;
        size_t ops_per_thread;
        size_t threads;
        minstd::atomic<void *> mailbox[cmp::MAX_THREADS * cmp::ALLOC_LIVE_WINDOW];
        minstd::atomic<uint64_t> allocations{0};
    };

    void alloc_own_thread(void *arg, size_t tid)
    {
        auto *ctx = static_cast<alloc_context *>(arg);
        cmp::rng r(tid);
        void *live[cmp::ALLOC_LIVE_WINDOW] = {};
        size_t sizes[cmp::ALLOC_LIVE_WINDOW] = {};
        uint64_t allocations = 0;

        for (size_t i = 0; i < ctx->ops_per_thread; ++i)
        {
            const size_t slot = r.next() % cmp::ALLOC_LIVE_WINDOW;

            if (live[slot] != nullptr)
            {
                ctx->resource->deallocate(live[slot], sizes[slot], 16);
                live[slot] = nullptr;
            }
            else
            {
                const size_t size = cmp::alloc_size(r);
                void *p = ctx->resource->allocate(size, 16);
                if (p != nullptr)
                {
                    *static_cast<volatile char *>(p) = 1;
                    live[slot] = p;
                    sizes[slot] = size;
                    ++allocations;
                }
            }
        }

        for (size_t slot = 0; slot < cmp::ALLOC_LIVE_WINDOW; ++slot)
        {
            if (live[slot] != nullptr)
            {
                ctx->resource->deallocate(live[slot], sizes[slot], 16);
            }
        }

        ctx->allocations.fetch_add(allocations);
    }

    void alloc_cross_thread(void *arg, size_t tid)
    {
        auto *ctx = static_cast<alloc_context *>(arg);
        cmp::rng r(tid);
        const size_t mailbox_slots = ctx->threads * cmp::ALLOC_LIVE_WINDOW;
        uint64_t allocations = 0;

        for (size_t i = 0; i < ctx->ops_per_thread; ++i)
        {
            const size_t size = cmp::alloc_size(r);
            void *p = ctx->resource->allocate(size, 16);
            if (p == nullptr)
            {
                continue;
            }
            *static_cast<size_t *>(p) = size;
            ++allocations;

            void *old = ctx->mailbox[r.next() % mailbox_slots].exchange(p, minstd::memory_order_acq_rel);
            if (old != nullptr)
            {
                ctx->resource->deallocate(old, *static_cast<size_t *>(old), 16);
            }
        }

        ctx->allocations.fetch_add(allocations);
    }

    result run_alloc(minstd::pmr::memory_resource &resource, bool cross, size_t threads, size_t ops_per_thread)
    {
        auto *ctx = new alloc_context();
        ctx->resource = &resource;
        ctx->ops_per_thread = ops_per_thread;
        ctx->threads = threads;
        for (auto &slot : ctx->mailbox)
        {
            slot.store(nullptr);
        }

        const double seconds = cmp::run_parallel(threads, cross ? alloc_cross_thread : alloc_own_thread, ctx);

        for (auto &slot : ctx->mailbox)
        {
            void *p = slot.load();
            if (p != nullptr)
            {
                resource.deallocate(p, *static_cast<size_t *>(p), 16);
            }
        }

        result res{seconds, threads * ops_per_thread, ctx->allocations.load()};
        delete ctx;
        return res;
    }

    constexpr size_t ARENA_BYTES = size_t{512} * 1024 * 1024;

    char *arena_buffer()
    {
        static char *buffer = nullptr;
        if (buffer == nullptr)
        {
            buffer = static_cast<char *>(aligned_alloc(4096, ARENA_BYTES));
            memset(buffer, 0, ARENA_BYTES); //  fault every page in once, outside any timed region
        }
        return buffer;
    }

    enum lockfree_resource_kind
    {
        LF_SINGLE_ARENA,
        LF_COMPOSITE,
        LF_BITBLOCK,
        LF_STATIC_ARENA
    };

    result run_lockfree_alloc(lockfree_resource_kind kind, bool cross, size_t threads, size_t ops_per_thread)
    {
        char *buffer = arena_buffer();

        switch (kind)
        {
        case LF_SINGLE_ARENA:
        {
            auto *resource = new minstd::pmr::lockfree_single_arena_resource_impl<minstd::platform::default_interrupt_policy>(buffer, ARENA_BYTES);
            const result r = run_alloc(*resource, cross, threads, ops_per_thread);
            delete resource;
            return r;
        }
        case LF_COMPOSITE:
        {
            auto *resource = new minstd::pmr::lockfree_composite_single_arena_resource<1000, 64, 1024, 32, 512, false>(buffer, ARENA_BYTES, cmp::MAX_THREADS);
            const result r = run_alloc(*resource, cross, threads, ops_per_thread);
            delete resource;
            return r;
        }
        case LF_BITBLOCK:
        {
            static minstd::pmr::malloc_free_wrapper_memory_resource upstream;
            auto *resource = new minstd::pmr::lockfree_bitblock_resource<64, 1024, 8, 512, false>(&upstream, cmp::MAX_THREADS);
            const result r = run_alloc(*resource, cross, threads, ops_per_thread);
            delete resource;
            return r;
        }
        case LF_STATIC_ARENA:
        default:
        {
            auto *resource = new minstd::pmr::lockfree_static_arena_resource(buffer, ARENA_BYTES);
            const result r = run_alloc(*resource, cross, threads, ops_per_thread);
            delete resource;
            return r;
        }
        }
    }

