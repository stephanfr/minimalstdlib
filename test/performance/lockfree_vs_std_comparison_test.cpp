    //  ---------------------------------------------------------------- measurement ----

    struct measurement
    {
        double median_ops_per_sec;
        double spread; //  (max - min) / median over the repetitions
        uint64_t checksum;
    };

    template <typename run_function>
    measurement measure(run_function run)
    {
        constexpr size_t MAX_REPS = 50;
        double rates[MAX_REPS];
        const size_t n = reps();
        uint64_t checksum = 0;

        for (size_t i = 0; i < n; ++i)
        {
            const result r = run();
            rates[i] = static_cast<double>(r.ops) / r.seconds;
            if (i == 0)
            {
                checksum = r.checksum;
            }
        }

        for (size_t i = 1; i < n; ++i) //  insertion sort: n is small
        {
            for (size_t j = i; j > 0 && rates[j - 1] > rates[j]; --j)
            {
                const double t = rates[j];
                rates[j] = rates[j - 1];
                rates[j - 1] = t;
            }
        }

        const double median = rates[n / 2];
        return {median, (rates[n - 1] - rates[0]) / median, checksum};
    }

