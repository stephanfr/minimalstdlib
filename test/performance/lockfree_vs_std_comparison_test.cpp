namespace
{
    void compare_allocators(bool cross)
    {
        const lockfree_resource_kind kinds[] = {LF_SINGLE_ARENA, LF_COMPOSITE, LF_BITBLOCK, LF_STATIC_ARENA};
        const char *names[] = {"lockfree_single_arena_resource", "lockfree_composite_single_arena_resource",
                               "lockfree_bitblock_resource", "lockfree_static_arena_resource"};
        const size_t ops = scaled(1'000'000);

        //  The std baselines are the same for every lock-free resource: measure them once per thread count.
        measurement std_cells[4][3];
        for (size_t t = 0; t < 4; ++t)
        {
            const size_t threads = THREAD_COUNTS[t];
            for (int kind = 0; kind < 3; ++kind)
            {
                std_cells[t][kind] = measure([&] { return cmp_std_alloc(kind, cross ? 1 : 0, threads, ops); });
            }
        }

        for (size_t k = 0; k < 4; ++k)
        {
            report_section section{};
            static char title[160];
            snprintf(title, sizeof(title), "%s, %s", names[k], cross ? "cross-thread frees" : "per-thread churn");
            section.title = title;
            section.description = cross
                                      ? "Each thread allocates 16-256 B blocks and swaps each into a shared mailbox of 64 slots per thread, "
                                        "freeing whatever it swaps out (usually another thread's block)."
                                      : "Each thread allocates 16-256 B blocks into a window of 64 live slots, freeing a slot's block "
                                        "when the random walk lands on it again.";
            section.column_names[0] = names[k];
            section.column_names[1] = "malloc/free";
            section.column_names[2] = "std::pmr::synchronized_pool_resource";
            section.column_names[3] = "std::pmr::unsynchronized_pool_resource + std::mutex";
            section.columns = 4;
            section.rows = 4;

            for (size_t t = 0; t < 4; ++t)
            {
                const size_t threads = THREAD_COUNTS[t];
                section.threads[t] = threads;
                section.cells[t][0] = measure([&] { return run_lockfree_alloc(kinds[k], cross, threads, ops); });
                section.cells[t][1] = std_cells[t][0];
                section.cells[t][2] = std_cells[t][1];
                section.cells[t][3] = std_cells[t][2];

                //  Same allocations on both sides (none failed).
                CHECK_EQUAL(std_cells[t][0].checksum, section.cells[t][0].checksum);
            }

            write_section(section);
        }
    }
}

