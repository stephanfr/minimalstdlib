    using list_type = minstd::skip_list<uint32_t, uint32_t, 16>;

    struct map_context
    {
        list_type *list;
        unsigned find_percent;
        size_t ops_per_thread;
        minstd::atomic<uint64_t> successes{0};
    };

    void map_body(void *arg, size_t tid)
    {
        auto *ctx = static_cast<map_context *>(arg);
        cmp::rng r(tid);
        uint64_t successes = 0;

        for (size_t i = 0; i < ctx->ops_per_thread; ++i)
        {
            const cmp::map_op op = cmp::next_map_op(r, ctx->find_percent);
            const uint32_t key = cmp::next_map_key(r);

            if (op == cmp::MAP_FIND)
            {
                successes += (ctx->list->find(key) != ctx->list->end()) ? 1 : 0;
            }
            else if (op == cmp::MAP_INSERT)
            {
                successes += ctx->list->insert(key, key) ? 1 : 0;
            }
            else
            {
                successes += ctx->list->remove(key) ? 1 : 0;
            }
        }

        ctx->successes.fetch_add(successes);
    }

    result run_lockfree_map(unsigned find_percent, size_t threads, size_t ops_per_thread)
    {
        auto *list = new list_type();
        for (uint32_t key = 0; key < cmp::MAP_KEY_RANGE; key += 2)
        {
            list->insert(key, key);
        }

        auto *ctx = new map_context();
        ctx->list = list;
        ctx->find_percent = find_percent;
        ctx->ops_per_thread = ops_per_thread;

        const double seconds = cmp::run_parallel(threads, map_body, ctx);
        result res{seconds, threads * ops_per_thread, ctx->successes.load()};
        delete ctx;
        delete list;
        return res;
    }

