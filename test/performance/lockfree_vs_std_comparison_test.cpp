    constexpr size_t MAX_COLUMNS = 4;

    struct report_section
    {
        const char *title;
        const char *description;
        const char *column_names[MAX_COLUMNS]; //  column 0: the lock-free class; the rest: std baselines
        size_t columns;
        size_t rows;
        size_t threads[8];
        measurement cells[8][MAX_COLUMNS];
    };

    const char *report_path()
    {
        static char path[256] = {0};

        if (path[0] == '\0')
        {
            const char *dir = "test/performance/reports";
            mkdir(dir, 0755);
            time_t now = time(nullptr);
            struct tm tm_now;
            localtime_r(&now, &tm_now);
            char stamp[32];
            strftime(stamp, sizeof(stamp), "%Y%m%d_%H%M%S", &tm_now);
            snprintf(path, sizeof(path), "%s/LOCKFREE_VS_STD_%s.md", dir, stamp);

            FILE *f = fopen(path, "w");
            if (f != nullptr)
            {
                fprintf(f, "# Lock-free classes vs. std + mutex\n\n");
                fprintf(f, "Generated by `LockfreeVsStdComparisonPerformanceTests` (%zu repetitions per cell, median shown; "
                           "`~` marks a cell whose spread (max - min) / median exceeds 10%%).  Throughput in millions of "
                           "operations per second; ratio = lock-free / std (> 1: lock-free faster).\n\n",
                        reps());
                fclose(f);
            }
        }

        return path;
    }

    void write_section(const report_section &section)
    {
        FILE *f = fopen(report_path(), "a");
        if (f == nullptr)
        {
            return;
        }

        fprintf(f, "## %s\n\n%s\n\n| threads | %s (Mops/s) |", section.title, section.description, section.column_names[0]);
        for (size_t c = 1; c < section.columns; ++c)
        {
            fprintf(f, " %s (Mops/s) | ratio |", section.column_names[c]);
        }
        fprintf(f, "\n|---:|---:|");
        for (size_t c = 1; c < section.columns; ++c)
        {
            fprintf(f, "---:|---:|");
        }
        fprintf(f, "\n");

        for (size_t r = 0; r < section.rows; ++r)
        {
            const measurement &lf = section.cells[r][0];
            fprintf(f, "| %zu | %.2f%s |", section.threads[r], lf.median_ops_per_sec / 1e6, lf.spread > 0.10 ? "~" : "");
            for (size_t c = 1; c < section.columns; ++c)
            {
                const measurement &m = section.cells[r][c];
                fprintf(f, " %.2f%s | %.2fx |", m.median_ops_per_sec / 1e6, m.spread > 0.10 ? "~" : "",
                        lf.median_ops_per_sec / m.median_ops_per_sec);
            }
            fprintf(f, "\n");
        }
        fprintf(f, "\n");
        fclose(f);

        printf("\n%s\n", section.title);
        for (size_t r = 0; r < section.rows; ++r)
        {
            printf("  %zu threads: %-28s %8.2f Mops/s", section.threads[r], section.column_names[0], section.cells[r][0].median_ops_per_sec / 1e6);
            for (size_t c = 1; c < section.columns; ++c)
            {
                printf(" | %s %.2f (%.2fx)", section.column_names[c], section.cells[r][c].median_ops_per_sec / 1e6,
                       section.cells[r][0].median_ops_per_sec / section.cells[r][c].median_ops_per_sec);
            }
            printf("\n");
        }
    }

