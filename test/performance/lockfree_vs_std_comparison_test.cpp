//  Lock-free classes against their closest standard C/C++ counterparts protected by a mutex.
//
//  Each lock-free kernel below mirrors a std kernel in external/std_baselines/std_runner.cpp operation for operation:
//  the same per-thread random streams, sizes, keys, op mixes and counts (comparison/workload.h), the same thread start
//  barrier and clock.  Each configuration is run REPS times and the median kept; the checksums of the two sides (work
//  actually done: allocations made, items moved, successful operations) are compared wherever the work is
//  deterministic, so neither side can skip work.  Results are appended to
//  test/performance/reports/LOCKFREE_VS_STD_<date>.md.
//
//  Environment: CMP_OPS_PERCENT scales every operation count (default 100), CMP_REPS sets the repetitions (default 5).

