    constexpr size_t STACK_CAPACITY = 1024;
    using spmc_type = minstd::lockfree::sp_mc_value_stack<uint32_t, STACK_CAPACITY>;

    struct spmc_context
    {
        spmc_type stack;
        size_t total;
        minstd::atomic<size_t> popped{0};
        minstd::atomic<uint64_t> checksum{0};
    };

    void spmc_body(void *arg, size_t tid)
    {
        auto *ctx = static_cast<spmc_context *>(arg);

        if (tid == 0)
        {
            for (uint32_t k = 1; k <= ctx->total; ++k)
            {
                while (!ctx->stack.push(k))
                {
                }
            }
            return;
        }

        uint64_t sum = 0;
        while (ctx->popped.load(minstd::memory_order_acquire) < ctx->total)
        {
            uint32_t value = 0;
            if (ctx->stack.pop(value))
            {
                sum += value;
                ctx->popped.fetch_add(1, minstd::memory_order_acq_rel);
            }
        }
        ctx->checksum.fetch_add(sum);
    }

    result run_lockfree_spmc_stack(size_t consumers, size_t total_items)
    {
        auto *ctx = new spmc_context();
        ctx->total = total_items;
        const double seconds = cmp::run_parallel(consumers + 1, spmc_body, ctx);
        result res{seconds, total_items, ctx->checksum.load()};
        delete ctx;
        return res;
    }

    struct pointer_node
    {
        pointer_node *next;
        uint64_t payload;
    };

    using pointer_tag = minstd::lockfree::tagged_ptr<pointer_node>;
    using pointer_stack = minstd::lockfree::intrusive_tagged_stack<pointer_node, pointer_tag, pointer_node *, &pointer_node::next>;

    struct pointer_adapter
    {
        pointer_node *to_link(pointer_node *p) const { return p; }
        pointer_node *to_node(pointer_node *p) const { return p; }
    };

    struct pointer_backoff
    {
        void operator()(size_t &retries) const { ++retries; }
    };

    struct pointer_stack_context
    {
        minstd::atomic<uint64_t> head{0};
        size_t ops_per_thread;
        minstd::atomic<uint64_t> pops{0};
    };

    void pointer_stack_body(void *arg, size_t)
    {
        auto *ctx = static_cast<pointer_stack_context *>(arg);
        pointer_adapter adapter;
        uint64_t pops = 0;

        for (size_t i = 0; i < ctx->ops_per_thread; ++i)
        {
            pointer_node *node = pointer_stack::pop(ctx->head, adapter, pointer_backoff{});
            if (node != nullptr)
            {
                ++pops;
                pointer_stack::push(ctx->head, *node, adapter, pointer_backoff{});
            }
        }

        ctx->pops.fetch_add(pops);
    }

    result run_lockfree_pointer_stack(size_t threads, size_t ops_per_thread)
    {
        auto *ctx = new pointer_stack_context();
        ctx->ops_per_thread = ops_per_thread;
        auto *nodes = new pointer_node[threads * 64];
        pointer_adapter adapter;
        for (size_t i = 0; i < threads * 64; ++i)
        {
            pointer_stack::push(ctx->head, nodes[i], adapter, pointer_backoff{});
        }

        const double seconds = cmp::run_parallel(threads, pointer_stack_body, ctx);
        result res{seconds, threads * ops_per_thread, ctx->pops.load()};
        delete[] nodes;
        delete ctx;
        return res;
    }

    struct exchange_context
    {
        minstd::elimination_array<uint64_t> exchange{0x9E3779B97F4A7C15ull};
        uint64_t *items;
        size_t producers;
        size_t items_per_producer;
        minstd::atomic<size_t> received{0};
        minstd::atomic<uint64_t> checksum{0};
    };

    void exchange_body(void *arg, size_t tid)
    {
        auto *ctx = static_cast<exchange_context *>(arg);
        const size_t total = ctx->producers * ctx->items_per_producer;

        if (tid < ctx->producers)
        {
            for (size_t k = 0; k < ctx->items_per_producer; ++k)
            {
                uint64_t *item = &ctx->items[tid * ctx->items_per_producer + k];
                while (!ctx->exchange.put_element(item))
                {
                }
            }
            return;
        }

        uint64_t sum = 0;
        while (ctx->received.load(minstd::memory_order_acquire) < total)
        {
            uint64_t *item = nullptr;
            if (ctx->exchange.get_element(item))
            {
                sum += *item;
                ctx->received.fetch_add(1, minstd::memory_order_acq_rel);
            }
        }
        ctx->checksum.fetch_add(sum);
    }

    result run_lockfree_exchange(size_t threads, size_t items_per_producer)
    {
        auto *ctx = new exchange_context();
        ctx->producers = threads / 2;
        ctx->items_per_producer = items_per_producer;
        ctx->items = new uint64_t[ctx->producers * items_per_producer];
        for (size_t i = 0; i < ctx->producers * items_per_producer; ++i)
        {
            ctx->items[i] = i + 1;
        }

        const double seconds = cmp::run_parallel(threads, exchange_body, ctx);
        result res{seconds, ctx->producers * items_per_producer, ctx->checksum.load()};
        delete[] ctx->items;
        delete ctx;
        return res;
    }

